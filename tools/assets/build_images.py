"""Builds every image the game draws at runtime and embeds it as Luau data.

Roblox can only show uploaded images, so instead of asset ids the pixels are packed into
ModuleScripts (src/shared/Images/*.lua) and turned into EditableImages on the client
(see src/client/ShotClient/ImageLoader.lua).

Inputs : tools/assets/source/logo.png          the game logo (used exactly as supplied)
         tools/assets/source/banner_logos.jpg  five logo variants for the stadium boards
         tools/assets/source/keeper_sheet.png  goalkeeper character sheet (kit textures)
Outputs: src/shared/Images/{Logo,Banners,Keeper}.lua and preview PNGs in assets/generated/

Run:  python3 tools/assets/build_images.py   (needs Pillow)

Packed format (base64): u16 width, u16 height, u16 palette size, palette RGBA bytes,
then LZ-compressed palette indices. LZ tokens: byte c < 128 -> c+1 literal bytes follow;
c >= 128 -> copy (c - 128 + 3) bytes from u16 offset back.
"""

import base64
import os
import struct

from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SOURCE = os.path.join(HERE, "source")
OUT_LUA = os.path.join(ROOT, "src", "shared", "Images")
OUT_PNG = os.path.join(ROOT, "assets", "generated")

# ---------------------------------------------------------------- packing


def lz_compress(data: bytes) -> bytes:
    out = bytearray()
    literals = bytearray()
    table = {}
    i, n = 0, len(data)

    def flush():
        nonlocal literals
        while literals:
            chunk = literals[:128]
            out.append(len(chunk) - 1)
            out.extend(chunk)
            literals = literals[128:]

    while i < n:
        best_len, best_off = 0, 0
        if i + 3 <= n:
            key = data[i:i + 3]
            for cand in table.get(key, ())[-24:]:
                off = i - cand
                if off > 65535:
                    continue
                length = 3
                while length < 130 and i + length < n and data[cand + length] == data[i + length]:
                    length += 1
                if length > best_len:
                    best_len, best_off = length, off
                    if length == 130:
                        break
        if best_len >= 3:
            flush()
            out.append(128 + best_len - 3)
            out.extend(struct.pack("<H", best_off))
            for k in range(i, i + best_len):
                if k + 3 <= n:
                    table.setdefault(data[k:k + 3], []).append(k)
            i += best_len
        else:
            if i + 3 <= n:
                table.setdefault(data[i:i + 3], []).append(i)
            literals.append(data[i])
            i += 1
    flush()
    return bytes(out)


def pack(image: Image.Image) -> str:
    image = image.convert("RGBA")
    w, h = image.size
    assert w <= 1024 and h <= 1024, "EditableImage max size is 1024x1024"
    quant = image.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    palette = quant.getpalette(rawmode="RGBA")
    indices = quant.tobytes()
    count = max(indices) + 1
    header = struct.pack("<HHH", w, h, count) + bytes(palette[: count * 4])
    return base64.b64encode(header + lz_compress(indices)).decode("ascii")


def write_module(name: str, images: dict, comment: str):
    lines = [f"-- Generated by tools/assets/build_images.py. Do not edit by hand.", f"-- {comment}", "return {"]
    total = 0
    for key, image in images.items():
        data = pack(image)
        total += len(data)
        wrapped = "\n".join(data[i:i + 160] for i in range(0, len(data), 160))
        lines.append(f'\t["{key}"] = [==[\n{wrapped}\n]==],')
        image.save(os.path.join(OUT_PNG, f"{name}_{key}.png"))
    lines.append("}")
    with open(os.path.join(OUT_LUA, f"{name}.lua"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{name}.lua: {len(images)} images, {total // 1024} KB")


