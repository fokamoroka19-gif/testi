MIRRORED = ["HeadSide", "UpperTorsoSide", "LowerTorsoSide", "UpperLegSide", "LowerLegSide", "UpperArmSide", "LowerArmSide", "GloveSide"]


def keeper_textures() -> dict:
    out = {}
    for name, box in KEEPER_BOXES.items():
        out[name] = sheet.crop(box).convert("RGBA")
    for name in MIRRORED:
        out[name + "R"] = out[name].transpose(Image.FLIP_LEFT_RIGHT)
    return out


def contact_sheet(images: dict, path: str):
    pad, scale = 10, 3
    width = sum(i.width * scale + pad for i in images.values()) + pad
    height = max(i.height for i in images.values()) * scale + 40
    cs = Image.new("RGBA", (min(width, 4000), height * (width // 4000 + 1)), (40, 40, 40, 255))
    x = y = pad
    d = ImageDraw.Draw(cs)
    for name, im in images.items():
        big = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
        if x + big.width > cs.width:
            x, y = pad, y + height
        cs.alpha_composite(big, (x, y + 20))
        d.text((x, y + 4), name, fill=(255, 255, 0, 255))
        x += big.width + pad
    cs.save(path)


